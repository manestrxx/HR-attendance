function getLang() {
  try { return localStorage.getItem('lang') || 'ar'; } catch { return 'ar'; }
}

function t(key, vars = {}) {
  const dict = I18N[getLang()] || I18N.ar;
  let s = dict[key] ?? I18N.ar[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

function errorText(data) {
  const code = data && data.error ? data.error : 'server_error';
  const dist = data?.distance == null ? '' : data.distance >= 1000
    ? `${(data.distance / 1000).toFixed(1)} ${getLang() === 'ar' ? 'كم' : 'km'}` : `${data.distance} ${getLang() === 'ar' ? 'م' : 'm'}`;
  return t('err_' + code, { s: data?.retry_after ?? '', since: data?.since ?? '', detail: data?.detail ?? '', site: data?.site ?? '', dist });
}

function applyI18n(root = document) {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-lang-toggle]').forEach((el) => { el.textContent = lang === 'ar' ? 'EN' : 'ع'; });
}

function toggleLang() {
  try { localStorage.setItem('lang', getLang() === 'ar' ? 'en' : 'ar'); } catch {}
  applyI18n();
  document.dispatchEvent(new Event('langchange'));
}

// تحويل الدقائق إلى نص مختصر: 25 د أو 1 س 5 د
function fmtMins(m) {
  const ar = getLang() === 'ar';
  if (m < 60) return ar ? `${m} د` : `${m}m`;
  const h = Math.floor(m / 60), r = m % 60;
  return ar ? `${h} س${r ? ` ${r} د` : ''}` : `${h}h${r ? ` ${r}m` : ''}`;
}

const escapeHtml = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// عرض التاريخ بشكل مقروء: 23 Oct 2026
function fmtDate(d) {
  if (!d) return '';
  return new Date(d + 'T12:00:00Z').toLocaleDateString(getLang() === 'ar' ? 'ar-OM-u-nu-latn' : 'en-GB',
    { timeZone: 'UTC', day: 'numeric', month: 'short', year: 'numeric' });
}
const fmtRange = (a, b) => (a === b || !b ? fmtDate(a) : `${fmtDate(a)} – ${fmtDate(b)}`);

async function api(url, options = {}) {
  const opts = { credentials: 'same-origin', ...options, headers: { ...(options.headers || {}) } };
  if (opts.body && !(opts.body instanceof Blob) && !(opts.body instanceof ArrayBuffer) && typeof opts.body !== 'string') {
    opts.headers['Content-Type'] = 'application/json';
    opts.body = JSON.stringify(opts.body);
  }
  try {
    const res = await fetch(url, opts);
    const data = await res.json().catch(() => ({ ok: false, error: res.status === 413 ? 'file_too_large' : 'server_error' }));
    return { status: res.status, ...data };
  } catch {
    return { ok: false, error: 'network' };
  }
}

// قراءة مرفق وتصغير الصور الكبيرة قبل الإرسال
async function readAttachment(file) {
  if (!file) return null;
  const toDataUrl = (blob) => new Promise((resolve, reject) => {
    const r = new FileReader(); r.onload = () => resolve(r.result); r.onerror = reject; r.readAsDataURL(blob);
  });
  if (file.type.startsWith('image/') && !/heic|heif/.test(file.type) && file.size > 900 * 1024) {
    try {
      const img = await createImageBitmap(file);
      const scale = Math.min(1, 1600 / Math.max(img.width, img.height));
      const canvas = document.createElement('canvas');
      canvas.width = Math.round(img.width * scale); canvas.height = Math.round(img.height * scale);
      canvas.getContext('2d').drawImage(img, 0, 0, canvas.width, canvas.height);
      const blob = await new Promise((r) => canvas.toBlob(r, 'image/jpeg', 0.82));
      return { name: file.name.replace(/\.\w+$/, '') + '.jpg', type: 'image/jpeg', data: await toDataUrl(blob) };
    } catch { /* نرسل الأصل */ }
  }
  return { name: file.name, type: file.type || 'application/octet-stream', data: await toDataUrl(file) };
}

